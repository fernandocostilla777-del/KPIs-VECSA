function diffSets(a, b) {
  const A = new Set(a);
  const B = new Set(b);
  return {
    onlyA: [...A].filter((x) => !B.has(x)),
    onlyB: [...B].filter((x) => !A.has(x)),
  };
}

async function sumAccounts(accounts) {
  if (!accounts.length) return 0;
  const mov = 'ISNULL(CTA_CARGO11,0)-ISNULL(CTA_ABONO11,0)';
  const sign = `CASE WHEN CTA_NATURALEZA='DEUD' THEN (${mov}) ELSE -(${mov}) END`;
  let total = 0;
  for (let i = 0; i < accounts.length; i += 80) {
    const batch = accounts.slice(i, i + 80);
    const params = {};
    const ph = batch.map((_, j) => `@a${j}`).join(', ');
    batch.forEach((a, j) => { params[`a${j}`] = a; });
    const rows = await query(`
      SELECT SUM(${sign}) AS t FROM CON_CTAS012025
      WHERE CTA_ACUMDET='DETA' AND CTA_NUMCTA IN (${ph})
    `, params);
    total += Number(rows[0]?.t || 0);
  }
  return total;
}

async function sumGpo(gpo) {
  const mov = 'ISNULL(CTA_CARGO11,0)-ISNULL(CTA_ABONO11,0)';
  const sign = `CASE WHEN CTA_NATURALEZA='DEUD' THEN (${mov}) ELSE -(${mov}) END`;
  const rows = await query(`
    SELECT SUM(${sign}) AS t FROM CON_CTAS012025
    WHERE CTA_ACUMDET='DETA' AND CTA_GPOCONT=@gpo
  `, { gpo });
  return Number(rows[0]?.t || 0);
}

